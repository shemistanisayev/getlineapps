// Extracts platform marks from the design's brand icons (design/rivaline/Mark.dc.html,
// design/serpline/Mark.dc.html). Third-party marks come only from the design (Simple Icons, CC0),
// unaltered. Output is committed: src/marks.generated.ts.
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const root = join(here, '..', '..', '..');

function parse(file, neutralStroke) {
  const src = readFileSync(join(root, file), 'utf8');
  const meta = {};
  for (const m of src.matchAll(/^(\w+): \['([^']+)', '([^']*)', '([^']*)'(?:, '(\w+)')?\]/gm)) {
    meta[m[1]] = { title: m[2], tint: m[3], fill: m[4], kind: m[5] ?? 'brand' };
  }
  const out = {};
  for (const m of src.matchAll(/<sc-if value="\{\{is\.(\w+)\}\}"[^>]*>([\s\S]*?)<\/sc-if>/g)) {
    const key = m[1];
    let inner = m[2].trim();
    const info = meta[key];
    if (!info) throw new Error(`No meta for ${key} in ${file}`);
    let mode = info.kind === 'neutral' ? 'stroke' : 'fill';
    let stroke;
    const nested = inner.match(/^<svg[^>]*stroke="([^"]+)"[^>]*>([\s\S]*)<\/svg>$/);
    if (nested) {
      mode = 'stroke';
      stroke = nested[1];
      inner = nested[2];
    }
    if (mode === 'stroke') stroke ??= neutralStroke;
    out[key] = {
      title: info.title,
      tint: info.tint,
      ...(mode === 'fill' ? { fill: info.fill } : { stroke }),
      svg: inner.replace(/><\/(path|rect|circle)>/g, '/>'),
    };
  }
  return out;
}

const riva = parse('design/rivaline/Mark.dc.html', '#475467');
const serp = parse('design/serpline/Mark.dc.html', '#1D4ED8');
const marks = { ...riva };
for (const [k, v] of Object.entries(serp)) {
  if (marks[k] && marks[k].svg !== v.svg) throw new Error(`Mark ${k} differs between designs`);
  marks[k] ??= v;
}
const ringed = ['mailchimp', 'snapchat', 'klarna'];
for (const k of ringed) if (marks[k]) marks[k].ring = true;

const body = `// Generated by scripts/marks.mjs from design/*/Mark.dc.html. Do not edit by hand.
// Third-party marks: Simple Icons (CC0). Trademarks of their owners, shown only to name what a tool supports.
export const MARK_DATA = ${JSON.stringify(marks, null, 2)} as const;
`;
writeFileSync(join(here, '..', 'src', 'marks.generated.ts'), body);
console.log(`${Object.keys(marks).length} marks: ${Object.keys(marks).join(', ')}`);
