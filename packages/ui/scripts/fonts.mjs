// Copies the self-hosted fonts into the repo (run once, output is committed).
// Web: variable woff2, latin + latin-ext (Azerbaijani needs latin-ext), from @fontsource-variable.
// PDF: static TTF weights for pdf-lib, from @expo-google-fonts. All fonts are SIL OFL 1.1.
import { copyFileSync, mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { createRequire } from 'node:module';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const require = createRequire(import.meta.url);
const pkgDir = (name) => dirname(require.resolve(`${name}/package.json`));

const webOut = join(here, '..', 'fonts');
const pdfOut = join(here, '..', '..', 'report', 'fonts');
mkdirSync(webOut, { recursive: true });
mkdirSync(pdfOut, { recursive: true });

const web = [
  { pkg: '@fontsource-variable/inter', family: 'Inter', file: 'inter', weights: '100 900' },
  {
    pkg: '@fontsource-variable/plus-jakarta-sans',
    family: 'Plus Jakarta Sans',
    file: 'plus-jakarta-sans',
    weights: '200 800',
  },
  {
    pkg: '@fontsource-variable/jetbrains-mono',
    family: 'JetBrains Mono',
    file: 'jetbrains-mono',
    weights: '100 800',
  },
];

let css = '/* Generated by scripts/fonts.mjs. Self-hosted, SIL OFL 1.1 (see fonts/OFL.txt). */\n';
for (const f of web) {
  const dir = pkgDir(f.pkg);
  const source = readFileSync(join(dir, 'index.css'), 'utf8');
  for (const subset of ['latin-ext', 'latin']) {
    const name = `${f.file}-${subset}-wght-normal.woff2`;
    copyFileSync(join(dir, 'files', name), join(webOut, name));
    const block = source.split('/*').find((b) => b.startsWith(` ${f.file}-${subset}-wght-normal `));
    const range = block?.match(/unicode-range:\s*([^;]+);/)?.[1];
    if (!range) throw new Error(`No unicode-range for ${name}`);
    css += `@font-face {
  font-family: '${f.family}';
  font-style: normal;
  font-display: swap;
  font-weight: ${f.weights};
  src: url('../fonts/${name}') format('woff2');
  unicode-range: ${range};
}
`;
  }
}
writeFileSync(join(here, '..', 'src', 'fonts.css'), css);

const pdf = [
  ['@expo-google-fonts/inter', '400Regular/Inter_400Regular.ttf'],
  ['@expo-google-fonts/inter', '600SemiBold/Inter_600SemiBold.ttf'],
  ['@expo-google-fonts/inter', '700Bold/Inter_700Bold.ttf'],
  ['@expo-google-fonts/plus-jakarta-sans', '800ExtraBold/PlusJakartaSans_800ExtraBold.ttf'],
  ['@expo-google-fonts/jetbrains-mono', '400Regular/JetBrainsMono_400Regular.ttf'],
];
for (const [pkg, rel] of pdf) {
  copyFileSync(join(pkgDir(pkg), rel), join(pdfOut, rel.split('/')[1]));
}
console.log('fonts copied');
for (const [out, from] of [
  [webOut, '@fontsource-variable/inter'],
  [pdfOut, '@fontsource-variable/inter'],
]) {
  const notice = `Inter, Plus Jakarta Sans and JetBrains Mono are licensed under the SIL Open Font License 1.1.
Copyright: The Inter Project Authors; The Plus Jakarta Sans Project Authors; The JetBrains Mono Project Authors.

${readFileSync(join(pkgDir(from), 'LICENSE'), 'utf8')}`;
  writeFileSync(join(out, 'OFL.txt'), notice);
}
